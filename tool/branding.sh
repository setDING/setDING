#!/usr/bin/env bash
# Generates every logo image from the SVG sources in app/branding/
# (docs/development/branding.md): the PNGs of the native splash screens
# (Android, iOS, via flutter_native_splash), the web splash images, the
# favicon, the web app icons, the README logo and the app icons of Android,
# iOS, Windows and Linux. The results are checked in, so only run
# this after changing the logo.
#
# Needs rsvg-convert (librsvg) and ImageMagick (magick).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP="$ROOT/app"
SRC="$APP/branding"
OUT="$SRC/generated"
WEB="$APP/web"

if ! command -v flutter >/dev/null 2>&1 && [ -x "$HOME/development/flutter/bin/flutter" ]; then
  export PATH="$HOME/development/flutter/bin:$PATH"
fi
for tool in rsvg-convert magick; do
  command -v "$tool" >/dev/null || { echo "branding: $tool is missing" >&2; exit 1; }
done

mkdir -p "$OUT" "$WEB/splash" "$WEB/icons" "$APP/linux/runner/resources"
svg() { rsvg-convert "$@"; }
# ImageMagick without date chunks, so unchanged images stay byte-identical.
magick() { command magick "${@:1:$#-1}" -define png:exclude-chunks=date,time "${@: -1}"; }

# Native splash. flutter_native_splash treats the images as 4x:
# mark 128 dp, wordmark 200 dp wide (as SplashScreen in logo.dart).
svg -w 512 -h 512 "$SRC/mark.svg" -o "$OUT/splash-mark.png"
# Android 12+: 288 dp icon, of which the inner 192 dp circle is visible.
magick -size 1152x1152 xc:none "$OUT/splash-mark.png" -gravity center \
  -composite "$OUT/splash-mark-android12.png"
svg -w 800 "$SRC/wordmark.svg" -o "$OUT/splash-wordmark.png"
svg -w 800 "$SRC/wordmark-dark.svg" -o "$OUT/splash-wordmark-dark.png"

# Logo with wordmark for the README.
python3 "$ROOT/tool/branding_lockup.py" "$SRC"

# Web splash (web/index.html) and icons.
cp "$SRC/mark.svg" "$SRC/wordmark.svg" "$SRC/wordmark-dark.svg" "$WEB/splash/"
svg -w 32 -h 32 "$SRC/mark.svg" -o "$WEB/favicon.png"
for size in 192 512; do
  svg -w "$size" -h "$size" "$SRC/mark.svg" -o "$WEB/icons/Icon-$size.png"
  # Maskable: the mark inside the 80 % safe zone on the splash color.
  inner=$((size * 62 / 100))
  svg -w "$inner" -h "$inner" "$SRC/mark.svg" -o "$OUT/mask-$size.png"
  magick -size "${size}x${size}" xc:'#FFFFFF' "$OUT/mask-$size.png" \
    -gravity center -composite "$WEB/icons/Icon-maskable-$size.png"
  rm "$OUT/mask-$size.png"
done

# App icons: the mark on the splash background (white), like the splash.
# icon <size> <mark %> <file>: opaque square icon.
icon() {
  local inner=$(($1 * $2 / 100))
  svg -w "$inner" -h "$inner" "$SRC/mark.svg" -o "$OUT/tmp-mark.png"
  magick -size "${1}x${1}" xc:'#FFFFFF' "$OUT/tmp-mark.png" \
    -gravity center -composite -alpha off "$3"
}
# Monochrome silhouette (Android 13+ themed icons): the pick with the chord
# diagram cut out, as alpha.
sed -e 's/fill="url(#g)"/fill="#000000"/' "$SRC/mark.svg" > "$OUT/tmp-mono.svg"

# Android: adaptive icon (108 dp layers, the mark inside the 66 dp safe zone)
# plus the legacy 48 dp icon.
RES="$APP/android/app/src/main/res"
mkdir -p "$RES/mipmap-anydpi-v26"
for d in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  name=${d%%:*}; scale=${d#*:}
  layer=$(python3 -c "print(round(108 * $scale))")
  legacy=$(python3 -c "print(round(48 * $scale))")
  mark=$(python3 -c "print(round(64 * $scale))")
  mkdir -p "$RES/mipmap-$name"
  svg -w "$mark" -h "$mark" "$SRC/mark.svg" -o "$OUT/tmp-mark.png"
  magick -size "${layer}x${layer}" xc:none "$OUT/tmp-mark.png" -gravity center \
    -composite "$RES/mipmap-$name/ic_launcher_foreground.png"
  svg -w "$mark" -h "$mark" "$OUT/tmp-mono.svg" -o "$OUT/tmp-mono.png"
  magick "$OUT/tmp-mono.png" \( +clone -alpha extract \) \
    \( "$OUT/tmp-mono.png" -alpha off -colorspace gray -negate \) \
    -delete 0 -compose multiply -composite -background black -alpha shape \
    -background none -gravity center -extent "${layer}x${layer}" \
    "$RES/mipmap-$name/ic_launcher_monochrome.png"
  icon "$legacy" 84 "$RES/mipmap-$name/ic_launcher.png"
done
cat > "$RES/mipmap-anydpi-v26/ic_launcher.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/branding.sh (docs/development/branding.md). -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
XML
cat > "$RES/values/ic_launcher_background.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/branding.sh (docs/development/branding.md). -->
<resources>
    <color name="ic_launcher_background">#FFFFFF</color>
</resources>
XML

# iOS: every size listed in AppIcon.appiconset, opaque.
IOS="$APP/ios/Runner/Assets.xcassets/AppIcon.appiconset"
for f in "$IOS"/Icon-App-*.png; do
  size=$(command magick identify -format '%w' "$f")
  icon "$size" 76 "$f"
done

# Windows: multi-size .ico, the mark on transparent.
for size in 16 24 32 48 64 128 256; do
  svg -w "$size" -h "$size" "$SRC/mark.svg" -o "$OUT/tmp-ico-$size.png"
done
magick "$OUT"/tmp-ico-{16,24,32,48,64,128,256}.png \
  "$APP/windows/runner/resources/app_icon.ico"

# Linux: window icon, installed into the bundle (linux/CMakeLists.txt).
svg -w 256 -h 256 "$SRC/mark.svg" -o "$APP/linux/runner/resources/app_icon.png"

rm -f "$OUT"/tmp-*

cd "$APP"
dart run flutter_native_splash:create
echo "branding: images generated"
