"""Builds single-colour logo SVGs for 3D-printed imprints (issue #1123) in
app/branding/imprint/ from the geometry of mark.svg and the paths of
wordmark.svg; see docs/development/branding.md.

Every file is one closed path (even-odd), one colour, sized in millimetres
(1 unit = 1 mm). Filled is the raised or embossed area. Compared with
mark.svg the bell has a thicker stem and a wider gap above its base, and the
list lines end with a clearance before the bell instead of running behind
it, so nothing is thinner than about 1 mm at the nominal size.

Run with `uv run tool/branding_imprint.py` (uv installs the dependencies).
"""
import os
import re

from shapely.affinity import scale, translate
from shapely.geometry import LineString, Polygon, box
from shapely.geometry.polygon import orient
from shapely.ops import unary_union
from svgpathtools import parse_path

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'app', 'branding')
OUT = os.path.join(SRC, 'imprint')


def pill(x, y, w, h, r):
    """Rounded rectangle as in mark.svg (rect with rx)."""
    r = min(r, w / 2, h / 2)
    return box(x + r, y + r, x + w - r, y + h - r).buffer(r, quad_segs=32)


def path_poly(d, n=24):
    """An SVG path as polygon; subpaths combine even-odd (letter holes)."""
    out = Polygon()
    for sub in parse_path(d).continuous_subpaths():
        pts = [(z.real, z.imag) for seg in sub
               for z in (seg.point(i / n) for i in range(n))]
        if len(pts) > 2:
            out = out.symmetric_difference(Polygon(pts).buffer(0))
    return out


# The bell of mark.svg: stem 16 instead of 10 wide, gap above the base 16
# instead of 11.
bell = unary_union([
    pill(238, 204, 36, 20, 8),
    pill(248, 218, 16, 32, 4),
    path_poly('M154 356C154 292 199 243 256 243C313 243 358 292 358 356Z', 64),
    pill(127, 372, 258, 30, 15),
])

# The set list of mark.svg (row top -> right end), 22 instead of 18 high.
# Each line ends 18 units before the bell with a round end; stubs shorter
# than 60 units are dropped.
ROWS = {95: 346, 143: 416, 191: 296, 239: 396, 287: 336}
clearance = bell.buffer(18)
pieces = []
for row, end in ROWS.items():
    cut = LineString([(96, row + 11), (end, row + 11)]).difference(clearance)
    for seg in getattr(cut, 'geoms', [cut]):
        x0, _, x1, _ = seg.bounds
        if x1 - x0 >= 60:
            p = pill(x0, row, x1 - x0, 22, 11)
            if p.distance(bell) >= 10:
                pieces.append(p)
lines = unary_union(pieces)
tile = pill(40, 40, 432, 432, 120)

wordmark_svg = open(os.path.join(SRC, 'wordmark.svg')).read()
word = unary_union([translate(path_poly(d), -17.82, -36.92)  # wordmark's <g> transform
                    for d in re.findall(r'\sd="([^"]+)"', wordmark_svg)])


def write(geom, name, width_mm, description):
    minx, miny, maxx, maxy = geom.bounds
    k = width_mm / (maxx - minx)
    geom = scale(translate(geom, -minx, -miny), k, k, origin=(0, 0))
    w, h = (maxx - minx) * k, (maxy - miny) * k
    d = []
    for p in getattr(geom, 'geoms', [geom]):
        p = orient(p)
        for ring in [p.exterior, *p.interiors]:
            d.append('M' + ' L'.join(f'{x:.3f} {y:.3f}'
                                     for x, y in list(ring.coords)[:-1]) + 'Z')
    with open(os.path.join(OUT, name), 'w') as f:
        f.write(
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{w:.2f}mm" '
            f'height="{h:.2f}mm" viewBox="0 0 {w:.3f} {h:.3f}">\n'
            f'<!-- setDING logo for 3D-printed imprints: {description}. '
            f'Generated by tool/branding_imprint.py; 1 unit = 1 mm, '
            f'filled = raised. -->\n'
            f'<path fill="#000" fill-rule="evenodd" d="{" ".join(d)}"/>\n'
            f'</svg>\n')


os.makedirs(OUT, exist_ok=True)
stamp = tile.difference(unary_union([bell, lines]))
write(stamp, 'imprint-stamp.svg', 30, 'tile filled, bell and list cut out')
write(unary_union([tile.difference(pill(66, 66, 380, 380, 94)), bell, lines]),
      'imprint-frame.svg', 30, 'tile as frame, bell and list raised')
write(bell, 'imprint-bell.svg', 25, 'bell only')
word_h = 124.78 * 2.6  # wordmark 2.6 x its own size, centred on the tile
write(unary_union([stamp, translate(scale(word, 2.6, 2.6, origin=(0, 0)),
                                    520, 256 - word_h / 2 + 6)]),
      'imprint-stamp-wordmark.svg', 80, 'stamp with the wordmark')
print(f'Wrote the imprint SVGs to {os.path.relpath(OUT, ROOT)}/')
